    private void guardarjButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarjButton1ActionPerformed
        // TODO add your handling code here:
        try {
            LocalDate fechaParse = LocalDate.parse(fechajTextField2.getText());
            float precioParse = Float.parseFloat(preciojTextField3.getText());
            if (ControlErrores.comprobarMatricula(matriculajTextField1.getText())) {
                if (ControlErrores.comprobarFecha(fechaParse)) {
                    if (ControlErrores.comprobarPrecio(precioParse)) {
                        controlActual.anadirCoche(matriculajTextField1.getText(), fechaParse, precioParse);
                        System.out.println("Se ha introducido el Coche!!");
                        matriculajTextField1.setText("");
                        fechajTextField2.setText("Fecha en formato(yyyy-mm-dd)");
                        preciojTextField3.setText("");
                        errorjLabel.setText("");
                    }else{
                        errorjLabel.setText("ERROR: No se ha introducido bien alguno de los atributos.");
                    }
                }else{
                    errorjLabel.setText("ERROR: No se ha introducido bien alguno de los atributos.");
                }
            }else{
                errorjLabel.setText("ERROR: No se ha introducido bien alguno de los atributos.");
            }
        } catch (NumberFormatException e) {
            errorjLabel.setText("ERROR: revise el formato de los atributos.");
        }catch(DateTimeParseException e){
            errorjLabel.setText("ERROR: revise el formato de los atributos.");
        }
    }//GEN-LAST:event_guardarjButton1ActionPerformed
    
